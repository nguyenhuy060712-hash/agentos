def g_land(seed, kind="hn"):
    r = R(seed, "ld")
    if kind == "hn": return f"024 3{r.randint(0, 999):03d} {r.randint(0, 9999):04d}"
    if kind == "hcm": return f"(028) 3{r.randint(0, 999):03d} {r.randint(0, 9999):04d}"
    return f"0225 3{r.randint(0, 999):03d} {r.randint(0, 999):03d}"
def g_mst(seed, kind=""):
    r = R(seed, "mst")
    while True:
        d = r.choice(["01", "03", "02", "04", "08", "31"]) + f"{r.randint(0, 9999999):07d}"
        c = 10 - sum(int(a) * b for a, b in zip(d, TAXW)) % 11
        if c < 10: return d + str(c) + ("-001" if kind == "b" else "")
def g_stk(seed, kind=""): r = R(seed, "stk"); n = r.randint(9, 16); return str(r.randint(1, 9)) + "".join(str(r.randint(0, 9)) for _ in range(n - 1))
def g_plate(seed, kind="car"):
    r = R(seed, "pl"); p = r.choice(PLATE_PROV); a = r.choice("ABCDEFGHKLMNPSTUVXYZ")
    if kind == "car": return f"{p}{a}-{r.randint(100, 999)}.{r.randint(0, 99):02d}"
    if kind == "car5": return f"{p}{a}-{r.randint(10000, 99999)}"
    if kind == "car2": return f"{p}{r.choice(['LD', 'MD', 'KD', 'AB'])}-{r.randint(100, 999)}.{r.randint(0, 99):02d}"
    if kind == "moto": return f"{p}-{a}{r.randint(1, 9)} {r.randint(100, 999)}.{r.randint(0, 99):02d}"
    if kind == "moto2": return f"{p}{a}{r.randint(1, 9)}-{r.randint(100, 999)}.{r.randint(0, 99):02d}"
    return f"{p}{a}-{r.randint(1000, 9999)}"
def g_card(seed, kind=""):
    r = R(seed, "cc"); d = [4] + [r.randint(0, 9) for _ in range(14)]
    s = sum((x * 2 - 9 if x * 2 > 9 else x * 2) if i % 2 == 0 else x for i, x in enumerate(d))   # check digit position 16 (index 15, not doubled)
    d.append((10 - s % 10) % 10); n = "".join(map(str, d))
    return f"{n[:4]} {n[4:8]} {n[8:12]} {n[12:]}" if kind == "sp" else n
def g_email(seed, kind=""):
    r = R(seed, "em"); return f"{r.choice(['an.nguyen', 'lan_pham', 'minh.tran88', 'hoa.le', 'dungvu', 'thu.ha', 'khoa.do'])}{r.randint(1, 99)}@{r.choice(['gmail.com', 'yahoo.com.vn', 'congty.vn', 'outlook.com', 'fpt.com'])}"
def g_ip(seed, kind=""): r = R(seed, "ip"); return f"{r.choice([10, 14, 27, 113, 171, 192])}.{r.randint(0, 255)}.{r.randint(0, 255)}.{r.randint(1, 254)}"
def g_dob(seed, kind=""):
    r = R(seed, "dob"); d, m, y = r.randint(1, 28), r.randint(1, 12), r.randint(1960, 2008)
    return {"": f"{d:02d}/{m:02d}/{y}", "dash": f"{d}-{m}-{y}", "dot": f"{d:02d}.{m:02d}.{y}"}[kind]
def g_pass(seed, kind=""): r = R(seed, "pp"); return r.choice("BCNP") + f"{r.randint(1000000, 9999999)}"
