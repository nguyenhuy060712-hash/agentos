def build():
    out = []
    allS = [(t, 'dev') for t in S] + [(t, 'holdout') for t in HOLD]
    rx = re.compile(r"\{\{(\w+)\|([^}]*)\}\}")
    for n, (tpl, split) in enumerate(allS):
        text, spans, pos = "", [], 0
        for m in rx.finditer(tpl):
            text += tpl[pos:m.start()]; pos = m.end(); typ, val = m.group(1), m.group(2)
            if val.startswith("@gen:"):
                parts = val[5:].split(":"); seed = parts[0]; kind = ":".join(parts[1:])
                if typ == "VN_PHONE" and kind.startswith("land"): val = g_land(seed, kind.split(":")[1] if ":" in kind else "hn")
                else: val = GEN[typ](seed, kind)
            spans.append({"start": len(text), "end": len(text) + len(val), "type": typ}); text += val
        text += tpl[pos:]
        out.append({"id": n, "split": split, "text": text, "spans": spans})
    return out

